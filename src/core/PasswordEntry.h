/**
 * @file PasswordEntry.h
 * @brief Объявление класса PasswordEntry.
 *
 * @details
 * Содержит интерфейс класса, представляющего
 * учётную запись пользователя в сервисе.
 *
 * Класс является частью ядра PaStorage и не зависит
 * от графического интерфейса или операционной системы.
 */

#ifndef PASTORAGE_PASSWORD_ENTRY_H
#define PASTORAGE_PASSWORD_ENTRY_H

#include <string>

/**
 * @class PasswordEntry
 * @brief Представляет запись учётной записи.
 *
 * @details
 * Хранит название сервиса и имя пользователя.
 *
 * Название сервиса задаётся при создании объекта
 * и не может быть изменено через публичный интерфейс.
 *
 * Имя пользователя можно получить и изменить
 * с помощью соответствующих методов.
 *
 * Класс не выполняет сохранение данных на диск
 * и не содержит криптографической функциональности.
 */

class PasswordEntry {
public:

    /**
     * @brief Создаёт запись с названием сервиса.
     *
     * @details
     * Инициализирует название сервиса переданным
     * значением. Имя пользователя остаётся пустым.
     *
     * @param title Название сервиса.
     *
     * @throws std::invalid_argument
     *         Если название сервиса пустое.
     */
    explicit PasswordEntry(std::string title);

    /**
     * @brief Создаёт запись с названием и логином.
     *
     * @details
     * Инициализирует оба поля объекта переданными
     * строковыми значениями.
     *
     * @param title Название сервиса.
     * @param username Имя пользователя.
     * @throws std::invalid_argument
     *         Если название сервиса пустое.
     */

    PasswordEntry(std::string title, std::string username);

    /**
     * @brief Возвращает название сервиса.
     *
     * @details
     * Метод не изменяет состояние объекта.
     * Возвращает отдельную копию строки.
     *
     * @return Название сервиса.
     */
    std::string title() const;

    /**
     * @brief Возвращает имя пользователя.
     *
     * @details
     * Метод не изменяет состояние объекта.
     * Возвращает отдельную копию строки.
     *
     * @return Текущее имя пользователя.
     */
    std::string username() const;

    /**
     * @brief Изменяет имя пользователя.
     *
     * @details
     * Заменяет ранее сохранённое имя пользователя
     * новым значением.
     *
     * Название сервиса при этом не изменяется.
     *
     * @param username Новое имя пользователя.
     */
    void setUsername(std::string username);

    private:
        /// Название сервиса.
        std::string title_;

        /// Имя пользователя.
        std::string username_;
};

#endif // PASTORAGE_PASSWORD_ENTRY_H
